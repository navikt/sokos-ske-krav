package no.nav.sokos.ske.krav.domain

import kotlinx.serialization.Serializable

@Serializable
data class KravDTO(
    val avsender: String,
    val belop: Double,
    val belopRente: Double,
    val corrId: String,
    val enhetBehandlende: String,
    val enhetBosted: String,
    val fagsystemId: String,
    val filnavn: String,
    val fremtidigYtelse: Double,
    val gjelderId: String,
    val kodeArsak: String,
    val kodeHjemmel: String,
    val kravId: Long,
    val kravidentifikatorSKE: String,
    val kravkode: String,
    val kravtype: String,
    val linjenummer: Int,
    val periodeFOM: String,
    val periodeTOM: String,
    val referansenummerGammelSak: String,
    val saksnummerNAV: String,
    val status: Status,
    val tidspunktOpprettet: String,
    val tidspunktSendt: String?,
    val tidspunktSisteStatus: String,
    val tilleggsfrist: String?,
    val transaksjonsDato: String,
    val utbetalDato: String?,
    val vedtaksDato: String,
)

fun Krav.toKravDTO() =
    KravDTO(
        avsender = avsender,
        belop = belop,
        belopRente = belopRente,
        corrId = corrId,
        enhetBehandlende = enhetBehandlende,
        enhetBosted = enhetBosted,
        fagsystemId = fagsystemId,
        filnavn = filnavn,
        fremtidigYtelse = fremtidigYtelse,
        gjelderId = gjelderId,
        kodeArsak = kodeArsak,
        kodeHjemmel = kodeHjemmel,
        kravId = kravId,
        kravidentifikatorSKE = kravidentifikatorSKE,
        kravkode = kravkode,
        kravtype = kravtype,
        linjenummer = linjenummer,
        periodeFOM = periodeFOM,
        periodeTOM = periodeTOM,
        referansenummerGammelSak = referansenummerGammelSak,
        saksnummerNAV = saksnummerNAV,
        status = status,
        tidspunktOpprettet = tidspunktOpprettet.toString(),
        tidspunktSendt = tidspunktSendt?.toString(),
        tidspunktSisteStatus = tidspunktSisteStatus.toString(),
        tilleggsfrist = tilleggsfrist?.toString(),
        transaksjonsDato = transaksjonsDato,
        utbetalDato = utbetalDato?.toString(),
        vedtaksDato = vedtaksDato.toString(),
    )
